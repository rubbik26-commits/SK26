import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Script, createContext } from "node:vm";

const source = readFileSync(new URL("../public/js/skyline-name.js", import.meta.url), "utf8");

function boot() {
  const values = new Map();
  const writes = [];
  const childDocument = {
    write(...parts) { writes.push(parts.join("")); },
    writeln(...parts) { writes.push(parts.join("") + "\n"); }
  };
  const blobs = [];
  class NativeBlob {
    constructor(parts, options = {}) {
      this.parts = [...parts];
      this.type = options.type || "";
      blobs.push(this);
    }
  }

  const logo = {
    value: "NYC Dev Intelligence logo",
    setAttribute(name, value) { if (name === "aria-label") this.value = value; }
  };
  const textNode = {
    nodeValue: "Create an API key restricted to nycremarketintel.com/*",
    parentNode: { nodeName: "B", closest() { return null; } }
  };
  let emitted = false;
  const document = {
    readyState: "complete",
    body: {},
    createTreeWalker() {
      return { nextNode() { if (emitted) return null; emitted = true; return textNode; } };
    },
    querySelectorAll() { return [logo]; }
  };
  const window = {
    location: { origin: "https://owner.skyline.example" },
    Blob: NativeBlob,
    open() { return { document: childDocument }; }
  };

  const context = createContext({
    window,
    document,
    localStorage: {
      getItem(key) { return values.has(key) ? values.get(key) : null; },
      setItem(key, value) { values.set(key, String(value)); }
    },
    URL,
    NodeFilter: { SHOW_TEXT: 4, FILTER_REJECT: 2, FILTER_ACCEPT: 1 },
    MutationObserver: class { observe() {} },
    requestAnimationFrame(fn) { fn(); },
    Object,
    Array,
    String
  });
  new Script(source, { filename: "skyline-name.js" }).runInContext(context);
  return { window, writes, blobs, logo, textNode, values };
}

test("main Owner UI removes legacy product and deployment identity", () => {
  const { logo, textNode, values } = boot();
  assert.equal(logo.value, "Skyline Properties logo");
  assert.equal(textNode.nodeValue, "Create an API key restricted to owner.skyline.example/*");
  assert.equal(values.get("ndi_user"), "Robert Khodadadian");
});

test("print/report windows are branded before the exact bundle writes their HTML", () => {
  const { window, writes } = boot();
  const child = window.open("");
  child.document.write(
    '<div class="brand">NYC RE Market Intel · Property Report</div>' +
    '<p>Prepared by William Lockley · Generated via NYC RE Market Intel.</p>'
  );
  assert.equal(writes.length, 1);
  assert.match(writes[0], /Skyline Properties · Property Report/);
  assert.match(writes[0], /Prepared by Robert Khodadadian/);
  assert.match(writes[0], /Generated via Skyline Properties\./);
  assert.doesNotMatch(writes[0], /NYC RE Market Intel|NYC Dev Intelligence|William Lockley/);
});

test("Owner Obsidian markdown points back to the active Skyline deployment", () => {
  const { window, blobs } = boot();
  const blob = new window.Blob([
    '# 1 Test Street\n\n' +
    '> Live dossier: https://nycremarketintel.com/?dossierBbl=1000000001#/dossier\n\n' +
    'Generated by NYC RE Market Intel\n'
  ], { type: "text/markdown" });

  assert.equal(blobs.length, 1);
  assert.equal(blob, blobs[0]);
  const text = blob.parts.join("");
  assert.match(text, /https:\/\/owner\.skyline\.example\/\?dossierBbl=1000000001#\/dossier/);
  assert.match(text, /Generated by Skyline Properties/);
  assert.doesNotMatch(text, /nycremarketintel\.com|NYC RE Market Intel/);
});

test("binary blobs are never modified by branding", () => {
  const { window, blobs } = boot();
  new window.Blob(["NYC RE Market Intel"], { type: "application/octet-stream" });
  assert.deepEqual(blobs.at(-1).parts, ["NYC RE Market Intel"]);
});