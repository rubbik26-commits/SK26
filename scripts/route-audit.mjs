// Route audit: enumerate every API pathname each router declares, then probe
// the running server to record which file actually answers each one.
//
//   node scripts/route-audit.mjs            # static declaration table
//   node scripts/route-audit.mjs --probe    # + runtime resolution (needs a
//                                           #   server started with route-probe)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const serverDir = path.join(root, "server");

const DECL = /router\s*\.\s*(get|post|put|patch|delete|all)\s*\(\s*(["'`])([^"'`]+)\2/g;
const MOUNT = /app\.use\(\s*([A-Za-z0-9_]+)\s*\)/g;

export function declarations() {
  const out = new Map(); // pathname -> [{file, method, line}]
  for (const file of readdirSync(serverDir).filter((f) => f.endsWith(".js"))) {
    const src = readFileSync(path.join(serverDir, file), "utf8");
    const lines = src.split("\n");
    for (let i = 0; i < lines.length; i++) {
      DECL.lastIndex = 0;
      let m;
      while ((m = DECL.exec(lines[i]))) {
        const [, method, , pathname] = m;
        if (!pathname.startsWith("/api/") && pathname !== "/healthz" && !pathname.startsWith("/__")) continue;
        const key = `${method.toUpperCase()} ${pathname}`;
        if (!out.has(key)) out.set(key, []);
        out.get(key).push({ file: `server/${file}`, line: i + 1 });
      }
    }
  }
  return out;
}

// Mount order as written in server.js, mapped back to the module each import
// name comes from — this is the order Express will consult the routers in.
export function mountOrder() {
  const src = readFileSync(path.join(root, "server.js"), "utf8");
  const imports = new Map();
  for (const m of src.matchAll(/import\s+(?:(\w+)|\{([^}]*)\})\s+from\s+"(\.\/server\/[^"]+)"/g)) {
    const [, def, named, file] = m;
    if (def) imports.set(def, file.replace("./", ""));
    for (const n of (named || "").split(",").map((x) => x.trim().split(" as ").pop()).filter(Boolean)) {
      imports.set(n, file.replace("./", ""));
    }
  }
  const order = [];
  MOUNT.lastIndex = 0;
  let m;
  while ((m = MOUNT.exec(src))) {
    const name = m[1];
    order.push({ name, file: imports.get(name) || "(inline)" });
  }
  return order;
}

function rank(order) {
  const byFile = new Map();
  order.forEach((o, i) => { if (!byFile.has(o.file)) byFile.set(o.file, i); });
  return byFile;
}

if (process.argv[1] && process.argv[1].endsWith("route-audit.mjs")) {
  const decl = declarations();
  const order = mountOrder();
  const fileRank = rank(order);

  const rows = [];
  for (const [key, sites] of [...decl.entries()].sort()) {
    const ranked = sites
      .map((s) => ({ ...s, rank: fileRank.has(s.file) ? fileRank.get(s.file) : 999 }))
      .sort((a, b) => a.rank - b.rank);
    rows.push({ key, sites: ranked, duplicate: ranked.length > 1 });
  }

  const dupes = rows.filter((r) => r.duplicate);
  let md = "# Route table\n\n";
  md += "Generated by `node scripts/route-audit.mjs`. \"First\" is the handler Express\n";
  md += "consults first, derived from the `app.use` order in server.js.\n\n";
  md += `Declared API routes: ${rows.length}. Declared in more than one router: ${dupes.length}.\n\n`;
  md += "## Routes declared by more than one router\n\n";
  md += "| Route | First (authoritative) | Shadowed |\n|---|---|---|\n";
  for (const r of dupes) {
    md += `| \`${r.key}\` | ${r.sites[0].file}:${r.sites[0].line} | ${r.sites.slice(1).map((s) => `${s.file}:${s.line}`).join("<br>")} |\n`;
  }
  md += "\n## Mount order\n\n";
  order.forEach((o, i) => { md += `${i + 1}. \`${o.name}\` — ${o.file}\n`; });
  md += "\n## All declared API routes\n\n| Route | Handlers (mount order) |\n|---|---|\n";
  for (const r of rows) md += `| \`${r.key}\` | ${r.sites.map((s) => `${s.file}:${s.line}`).join("<br>")} |\n`;

  writeFileSync(path.join(root, "docs/release/route-table.md"), md);
  console.log(`routes=${rows.length} duplicated=${dupes.length}`);
  for (const r of dupes) console.log(`  ${r.key}\n     first: ${r.sites[0].file}:${r.sites[0].line}\n     also:  ${r.sites.slice(1).map((s) => s.file + ":" + s.line).join(", ")}`);
}
